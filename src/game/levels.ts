/**
 * Уровни Рисинки.
 *
 * Чем выше набранная скидка, тем увереннее выглядит маскот. Это единственная
 * механика в игре, которая ничего не начисляет: уровень — следствие процента,
 * а не источник преимущества. Поэтому он и живёт здесь, рядом с экономикой, а
 * не в компоненте: правило детерминировано и должно проверяться тестом, а не
 * глазами на экране.
 *
 * Границы принадлежат старшему уровню: ровно десять процентов — уже второй.
 * Иначе гость, добравшийся до круглого числа, видел бы прежнего маскота и
 * решил, что уровень не засчитали.
 */

export const MASCOT_LEVELS = [1, 2, 3] as const;

export type MascotLevel = (typeof MASCOT_LEVELS)[number];

/** Нижние границы второго и третьего уровня в процентах скидки. */
export const SECOND_LEVEL_AT = 10;
export const THIRD_LEVEL_AT = 20;

export function mascotLevelFor(percent: number): MascotLevel {
  if (percent >= THIRD_LEVEL_AT) {
    return 3;
  }
  if (percent >= SECOND_LEVEL_AT) {
    return 2;
  }
  return 1;
}
