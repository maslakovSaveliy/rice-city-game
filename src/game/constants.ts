/**
 * Константы экономики.
 *
 * ВАЖНО: ни одно значение здесь не подбирается «на глаз». Любое изменение
 * проверяется симулятором персон в `economy.balance.test.ts` — тесты падают,
 * если средний гость перестаёт попадать в коридор 10–13%.
 *
 * ЮРИДИЧЕСКОЕ ОГРАНИЧЕНИЕ: начисление зёрен и расчёт скидки полностью
 * детерминированы. Случайность в награде превращает акцию в стимулирующую
 * лотерею по 138-ФЗ со всеми последствиями. `Math.random()` в этом модуле
 * и во всём `src/game` запрещён.
 */

/**
 * Потолок скидки в процентах.
 *
 * В отличие от прежней тридцатки этот потолок достижим: за час его берут
 * залипший гость, взрослый-максималист и автокликер. Это следствие решения
 * владельца оставить среднего гостя в 10–13% при вдвое меньшем максимуме —
 * развести верхние персоны под таким потолком нельзя арифметически. Побочный
 * эффект скорее полезный: накрутка перестаёт давать преимущество над честной
 * игрой, все упираются в одно и то же число.
 */
export const DISCOUNT_MAX = 15;

/**
 * Стоимость первого процента в зёрнах. При базовом тапе это около десяти
 * нажатий — гость видит движение в первые секунды.
 *
 * Масштаб намеренно крупный: счётчик в сотнях тысяч читается как достижение,
 * а мелкие числа в клике ощущаются скупо.
 */
export const FIRST_PERCENT_COST = 750;

/**
 * Каждый следующий процент дороже предыдущего во столько раз.
 *
 * Значение подобрано симулятором, а не интуицией: улучшения компаундируются
 * гораздо сильнее, чем кажется на бумаге, и разрыв между казуалом и
 * автокликером за час достигает пяти порядков.
 *
 * Поднято с 1.84 вместе со снижением потолка до 15%. На прежней кривой средний
 * гость садился ровно на 13% — впритык к новому максимуму, и всё, что выше
 * него, схлопывалось в потолок. С этим основанием средний берёт 11%, а между
 * ним и потолком остаётся ступень для увлечённого ребёнка.
 */
export const DISCOUNT_COST_GROWTH = 2.2;

/** Зёрен за один тап без улучшений и без комбо. */
export const BASE_TAP_VALUE = 10;

/** Длительность сессии. */
export const SESSION_DURATION_MS = 60 * 60 * 1000;

/**
 * Через сколько после фиксации скидки игра снова доступна. Это и есть рабочее
 * определение «нового визита» — авторизации нет, опереться больше не на что.
 */
export const FIX_LOCK_MS = 6 * 60 * 60 * 1000;

/** Прирост жара за один засчитанный тап. */
export const HEAT_PER_TAP = 0.1;

/** Затухание жара в секунду при бездействии. */
export const HEAT_DECAY_PER_SEC = 0.25;

/** Потолок жара. Множитель к тапу равен `1 + heat`, то есть максимум ×2. */
export const HEAT_MAX = 1;

/**
 * Корзина токенов для тапов: пополняется `TAP_RATE_LIMIT` в секунду, ёмкость
 * равна `TAP_BURST`. Быстрый ребёнок на 6–8 тапах в секунду её не исчерпывает,
 * скрипт на 20+ обрезается до 15.
 *
 * Ёмкость заметно больше секундного лимита, потому что сервер получает тапы
 * пачками раз в `SYNC_INTERVAL_MS`. При ёмкости 15 честный ребёнок, натапавший
 * тридцать раз за окно синхронизации, потерял бы половину. Запас взят на три
 * окна — с поправкой на задержки сети. На средний темп за час это не влияет:
 * ограничение задаёт скорость пополнения, а не ёмкость.
 */
export const TAP_RATE_LIMIT = 15;
export const TAP_BURST = 45;

/** Как часто клиент отправляет накопленные тапы на сервер. */
export const SYNC_INTERVAL_MS = 2_000;

/**
 * Верхняя граница тапов в одном запросе. Всё сверх этого отбрасывается ещё до
 * применения — иначе враждебный клиент заказывал бы миллион итераций цикла.
 * Потерь для честного игрока нет: больше `TAP_BURST` корзина всё равно не даст.
 */
export const MAX_TAPS_PER_BATCH = TAP_BURST;

/**
 * Потолок пассивного дохода: помощники за сессию не могут принести больше этой
 * доли от того, что гость натапал руками.
 *
 * Это структурная гарантия, а не подкрутка чисел. Без неё любой пассив,
 * достаточно сильный чтобы его стоило покупать, позволял обогнать играющего,
 * просто оставив экран включённым. Перепробовано пять наборов констант — тот,
 * кто играет, обгонял того, кто положил телефон, только ценой того, что
 * помощники становились заведомо невыгодной покупкой.
 */
export const PASSIVE_CAP_RATIO = 0.6;

/** Шаг игрового цикла для пассивного дохода и затухания жара. */
export const TICK_INTERVAL_MS = 100;

/**
 * Максимальный интервал, который засчитывается за один шаг. Защита от «дыр»:
 * если вкладка была свёрнута или процесс подвис, наивный расчёт по разнице
 * времени начислил бы пассив за всё это время. Пассив положен только за
 * реально проведённое в игре время.
 */
