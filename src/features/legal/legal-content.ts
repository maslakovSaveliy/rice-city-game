/**
 * Год добавляется вручную: с `year: "numeric"` Intl отдаёт «27 июля 2026 г.»,
 * а в тексте правил уместнее полная форма «27 июля 2026 года».
 */
const dayMonthFormatter = new Intl.DateTimeFormat("ru-RU", {
  day: "numeric",
  month: "long",
  timeZone: "UTC",
});

export function formatCampaignDate(timestamp: number): string {
  const date = new Date(timestamp);
  return `${dayMonthFormatter.format(date)} ${date.getUTCFullYear()} года`;
}

